package io.github.llm4j.eval.report;

import static io.github.llm4j.eval.report.EvalReportWriter.esc;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeSet;

/**
 * Renders the single-file HTML dashboard. The page is fully server-rendered, so it is complete
 * without JavaScript (email attachments, CI artifact viewers and locked-down Jenkins all work);
 * the small script only adds search, filtering, sorting, CSV export and a theme toggle. There are
 * no external requests, and every dynamic value passes through {@link EvalReportWriter#esc}.
 */
final class HtmlDashboard {

    /** More failing evaluations than this start collapsed, so the page stays scannable. */
    private static final int AUTO_OPEN_FAILURES = 25;

    /** Heatmap rows shown (worst tests first); the rest are summarised in a note. */
    private static final int HEATMAP_ROWS = 120;

    private static final int CHANGE_LIST_LIMIT = 15;

    private static final String CSS = resource("dashboard.css");
    private static final String JS = resource("dashboard.js");

    private HtmlDashboard() {}

    private static String resource(String name) {
        try (InputStream in = HtmlDashboard.class.getResourceAsStream(name)) {
            if (in == null) {
                throw new IllegalStateException("Missing dashboard resource " + name);
            }
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    static String render(ReportAnalysis a) {
        StringBuilder sb = new StringBuilder(16_384 + a.total * 700);
        sb.append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">")
                .append("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
                .append("<title>eval4j report</title><style>")
                .append(CSS)
                .append("</style></head><body>");
        header(sb, a);
        sb.append("<div class=\"wrap\">");
        cards(sb, a);
        changes(sb, a);
        metrics(sb, a);
        trends(sb, a);
        heatmap(sb, a);
        evaluations(sb, a);
        tests(sb, a);
        sb.append("<footer>Generated by eval4j · self-contained report, no external requests</footer>")
                .append("</div><script>")
                .append(JS)
                .append("</script></body></html>");
        return sb.toString();
    }

    // --- header & summary ------------------------------------------------------------------

    private static void header(StringBuilder sb, ReportAnalysis a) {
        String[] verdict = verdict(a);
        EvalReportWriter.RunInfo run = a.run;
        sb.append("<header class=\"top\"><div class=\"wrap\"><div class=\"brand\">eval<span>4j</span></div>")
                .append("<span class=\"verdict ")
                .append(verdict[0])
                .append("\">")
                .append(verdict[1])
                .append("</span><div class=\"meta\">run <code>")
                .append(esc(run.runId()))
                .append("</code> · ")
                .append(esc(run.startedAt()))
                .append(duration(run))
                .append(
                        run.gitSha() == null
                                ? ""
                                : " · commit <code>" + esc(Charts.shortSha(run.gitSha())) + "</code>")
                .append("</div><nav class=\"tabs\"><a href=\"#metrics\">Metrics</a>");
        if (a.timeline.size() > 1) {
            sb.append("<a href=\"#trends\">Trends</a>");
        }
        sb.append("<a href=\"#heatmap\">Heatmap</a><a href=\"#records\">Evaluations</a>");
        if (run.tests() != null && !run.tests().isEmpty()) {
            sb.append("<a href=\"#tests\">Tests</a>");
        }
        sb.append("</nav><button id=\"theme\" class=\"js-only\" type=\"button\" title=\"Toggle theme\">")
                .append("◐ Theme</button></div></header>");
    }

    private static String duration(EvalReportWriter.RunInfo run) {
        try {
            Duration d = Duration.between(Instant.parse(run.startedAt()), Instant.parse(run.endedAt()));
            if (d.isNegative()) {
                return "";
            }
            return d.toMinutes() > 0
                    ? " · took " + d.toMinutes() + "m " + d.toSecondsPart() + "s"
                    : " · took " + d.toMillis() / 1000.0 + "s";
        } catch (RuntimeException e) {
            return "";
        }
    }

    /** CSS class and label of the headline verdict. */
    private static String[] verdict(ReportAnalysis a) {
        if (a.total == 0 && a.failedTests() == 0) {
            return new String[] {"none", "NO EVALUATIONS"};
        }
        if (a.passed < a.total || a.failedTests() > 0) {
            return new String[] {"fail", "FAILING"};
        }
        if (a.hasRegression()) {
            return new String[] {"reg", "REGRESSION"};
        }
        return new String[] {"pass", "PASSING"};
    }

    private static void cards(StringBuilder sb, ReportAnalysis a) {
        sb.append("<div class=\"cards\">");
        card(sb, "Evaluations", String.valueOf(a.total), "");
        card(sb, "Passed", a.passed + " / " + a.total, a.passed == a.total ? "pass" : "fail");
        card(
                sb,
                "Pass rate",
                a.total == 0 ? "n/a" : String.format(Locale.ROOT, "%.0f%%", 100.0 * a.passRate),
                a.total == 0 ? "" : a.passed == a.total ? "pass" : "fail");
        if (a.total > 0) {
            card(sb, "Average score", String.format(Locale.ROOT, "%.3f", a.averageScore), "");
        }
        if (a.run.tests() != null && !a.run.tests().isEmpty()) {
            long failed = a.failedTests();
            card(
                    sb,
                    "Tests",
                    (a.run.tests().size() - failed) + " / " + a.run.tests().size(),
                    failed == 0 ? "pass" : "fail");
        }
        if (a.judgedMillis > 0) {
            card(sb, "Judge time", seconds(a.judgedMillis), "");
        }
        long regressed = a.metrics.values().stream().filter(ReportAnalysis.MetricStats::regressed).count();
        if (regressed > 0) {
            card(sb, "Regressed metrics", String.valueOf(regressed), "warn");
        }
        if (a.previous != null && a.previous.passRate() != null && a.total > 0) {
            double d = 100.0 * (a.passRate - a.previous.passRate());
            card(sb, "Δ pass rate", String.format(Locale.ROOT, "%+.1f pts", d), d < 0 ? "fail" : "");
        }
        sb.append("</div>");
    }

    private static void card(StringBuilder sb, String label, String value, String cls) {
        sb.append("<div class=\"card ")
                .append(cls)
                .append("\"><span>")
                .append(esc(label))
                .append("</span><b>")
                .append(esc(value))
                .append("</b></div>");
    }

    private static String seconds(long ms) {
        return ms < 60_000
                ? String.format(Locale.ROOT, "%.1fs", ms / 1000.0)
                : String.format(Locale.ROOT, "%dm %ds", ms / 60_000, (ms % 60_000) / 1000);
    }

    // --- changes since previous run --------------------------------------------------------

    private static void changes(StringBuilder sb, ReportAnalysis a) {
        if (!a.hasComparison()) {
            return;
        }
        sb.append("<h2>Since the previous run <small>")
                .append(esc(a.previous.timestamp()))
                .append(
                        a.previous.gitSha() == null
                                ? ""
                                : " · commit " + esc(Charts.shortSha(a.previous.gitSha())))
                .append(" · ")
                .append(a.newCases)
                .append(" new case(s)</small></h2><div class=\"changes\">");
        changeList(sb, a, "Newly failing", a.newFailures, "down");
        changeList(sb, a, "Fixed", a.fixed, "up");
        changeList(sb, a, "Score dropped", a.worse, "down");
        changeList(sb, a, "Score improved", a.better, "up");
        sb.append("</div>");
    }

    private static void changeList(
            StringBuilder sb,
            ReportAnalysis a,
            String title,
            List<ReportAnalysis.CaseChange> list,
            String cls) {
        sb.append("<div class=\"panel\"><h3>")
                .append(esc(title))
                .append(" (")
                .append(list.size())
                .append(")</h3>");
        if (list.isEmpty()) {
            sb.append("<div class=\"none\">none</div>");
        } else {
            sb.append("<ul>");
            list.stream()
                    .sorted(Comparator.comparingDouble(c -> cls.equals("down") ? c.delta() : -c.delta()))
                    .limit(CHANGE_LIST_LIMIT)
                    .forEach(
                            c -> {
                                EvalRecord r = a.records.get(c.recordIndex());
                                sb.append("<li><a href=\"#e")
                                        .append(c.recordIndex())
                                        .append("\">")
                                        .append(esc(shortTest(r)))
                                        .append(" · ")
                                        .append(esc(r.metric()))
                                        .append("</a> <span class=\"num ")
                                        .append(cls)
                                        .append("\">")
                                        .append(String.format(Locale.ROOT, "%.2f → %.2f", c.previous(), c.current()))
                                        .append("</span></li>");
                            });
            if (list.size() > CHANGE_LIST_LIMIT) {
                sb.append("<li class=\"none\">… and ")
                        .append(list.size() - CHANGE_LIST_LIMIT)
                        .append(" more</li>");
            }
            sb.append("</ul>");
        }
        sb.append("</div>");
    }

    // --- metrics & trends ------------------------------------------------------------------

    private static void metrics(StringBuilder sb, ReportAnalysis a) {
        sb.append("<h2 id=\"metrics\">Metrics <small>click a header to sort</small></h2>");
        if (a.metrics.isEmpty()) {
            sb.append("<div class=\"panel empty\">No judged evaluations were recorded.</div>");
            return;
        }
        sb.append("<div class=\"panel\"><table id=\"metrics-table\" class=\"sortable\"><thead><tr>")
                .append("<th>Metric</th><th>Average</th><th>Min</th><th>Median</th><th>Pass rate</th>")
                .append("<th>Distribution</th><th>Baseline Δ</th><th>Previous Δ</th><th>Trend</th>")
                .append("</tr></thead><tbody>");
        for (ReportAnalysis.MetricStats m : a.metrics.values()) {
            sb.append(m.regressed() ? "<tr class=\"reg\">" : "<tr>")
                    .append("<td>")
                    .append(esc(m.metric()))
                    .append("</td><td class=\"num\">")
                    .append(Charts.scoreBar(m.average(), m.threshold()))
                    .append(" ")
                    .append(String.format(Locale.ROOT, "%.3f", m.average()))
                    .append("</td><td class=\"num\">")
                    .append(String.format(Locale.ROOT, "%.3f", m.min()))
                    .append("</td><td class=\"num\">")
                    .append(String.format(Locale.ROOT, "%.3f", m.median()))
                    .append("</td><td class=\"num\">")
                    .append(m.passed())
                    .append('/')
                    .append(m.count())
                    .append("</td><td>")
                    .append(Charts.histogram(m.histogram(), m.threshold()))
                    .append("</td><td class=\"num ")
                    .append(deltaClass(m.baselineDelta()))
                    .append("\">")
                    .append(delta(m.baselineDelta()))
                    .append("</td><td class=\"num ")
                    .append(deltaClass(m.previousDelta()))
                    .append("\">")
                    .append(delta(m.previousDelta()))
                    .append("</td><td>")
                    .append(Charts.sparkline(m.trend()))
                    .append("</td></tr>");
        }
        sb.append("</tbody></table></div>");
    }

    private static String delta(Double d) {
        return d == null ? "–" : String.format(Locale.ROOT, "%+.3f", d);
    }

    private static String deltaClass(Double d) {
        if (d == null || Math.abs(d) < 0.0005) {
            return "flat";
        }
        return d > 0 ? "up" : "down";
    }

    private static void trends(StringBuilder sb, ReportAnalysis a) {
        if (a.timeline.size() < 2) {
            return;
        }
        List<String> names = new ArrayList<>(a.metrics.keySet());
        List<String> shown = names.size() > 8 ? names.subList(0, 8) : names;
        sb.append("<h2 id=\"trends\">Trends <small>last ")
                .append(a.timeline.size())
                .append(" runs · hover a point for details</small></h2><div class=\"panel\">")
                .append(Charts.trendChart(a.timeline, shown))
                .append("<div class=\"legend\">");
        for (int i = 0; i < shown.size(); i++) {
            sb.append("<span><svg width=\"10\" height=\"10\"><rect width=\"10\" height=\"10\" rx=\"2\" fill=\"")
                    .append(Charts.color(i))
                    .append("\"/></svg> ")
                    .append(esc(shown.get(i)))
                    .append("</span>");
        }
        sb.append("<span>- - pass rate</span>");
        if (names.size() > shown.size()) {
            sb.append("<span>+").append(names.size() - shown.size()).append(" more metrics not drawn</span>");
        }
        sb.append("</div></div>");
    }

    // --- heatmap ---------------------------------------------------------------------------

    private static void heatmap(StringBuilder sb, ReportAnalysis a) {
        if (a.groups.isEmpty() || a.metrics.isEmpty()) {
            return;
        }
        List<String> metricNames = new ArrayList<>(a.metrics.keySet());
        record Row(ReportAnalysis.TestGroup group, double worst) {}
        List<Row> rows = new ArrayList<>(a.groups.size());
        for (ReportAnalysis.TestGroup g : a.groups) {
            double worst = 1;
            for (int idx : g.recordIndexes()) {
                worst = Math.min(worst, a.records.get(idx).score());
            }
            rows.add(new Row(g, worst));
        }
        rows.sort(Comparator.comparingDouble(Row::worst));
        sb.append("<h2 id=\"heatmap\">Heatmap <small>tests × metrics, worst first · click a cell to open it")
                .append("</small></h2><div class=\"panel\"><table class=\"heat\"><thead><tr><th></th>");
        for (String m : metricNames) {
            sb.append("<th>").append(esc(m)).append("</th>");
        }
        sb.append("</tr></thead><tbody>");
        int shown = Math.min(HEATMAP_ROWS, rows.size());
        for (int r = 0; r < shown; r++) {
            ReportAnalysis.TestGroup g = rows.get(r).group();
            sb.append("<tr><th class=\"rowh\" title=\"")
                    .append(esc(g.key()))
                    .append("\">")
                    .append(esc(shortName(g.suite(), g.testName())))
                    .append("</th>");
            for (String m : metricNames) {
                int worstIdx = -1;
                for (int idx : g.recordIndexes()) {
                    EvalRecord rec = a.records.get(idx);
                    if (rec.metric().equals(m)
                            && (worstIdx < 0 || rec.score() < a.records.get(worstIdx).score())) {
                        worstIdx = idx;
                    }
                }
                if (worstIdx < 0) {
                    sb.append("<td class=\"none\">·</td>");
                    continue;
                }
                EvalRecord rec = a.records.get(worstIdx);
                sb.append("<td class=\"hm h")
                        .append((int) Math.round(rec.score() * 10))
                        .append(rec.passed() ? "" : " f")
                        .append("\"><a href=\"#e")
                        .append(worstIdx)
                        .append("\" title=\"")
                        .append(esc(m))
                        .append(" · threshold ")
                        .append(String.format(Locale.ROOT, "%.2f", rec.threshold()))
                        .append("\">")
                        .append(String.format(Locale.ROOT, "%.2f", rec.score()))
                        .append("</a></td>");
            }
            sb.append("</tr>");
        }
        sb.append("</tbody></table>");
        if (rows.size() > shown) {
            sb.append("<div class=\"empty\">Showing the ")
                    .append(shown)
                    .append(" lowest-scoring of ")
                    .append(rows.size())
                    .append(" tests; all are listed under Evaluations.</div>");
        }
        sb.append("</div>");
    }

    // --- evaluations -----------------------------------------------------------------------

    private static void evaluations(StringBuilder sb, ReportAnalysis a) {
        sb.append("<h2 id=\"records\">Evaluations <small>failures first · click a row for the case")
                .append(" detail</small></h2>");
        if (a.records.isEmpty()) {
            sb.append("<div class=\"panel empty\">No judged evaluations were recorded.</div>");
            return;
        }
        sb.append("<div class=\"toolbar\"><input id=\"q\" type=\"search\" placeholder=\"Search (press /)\"")
                .append(" aria-label=\"Search evaluations\"><select id=\"st\" aria-label=\"Status\">")
                .append("<option value=\"all\">All results</option><option value=\"fail\">Failed</option>")
                .append("<option value=\"pass\">Passed</option></select><select id=\"mt\" aria-label=\"Metric\">")
                .append("<option value=\"all\">All metrics</option>");
        for (String m : new TreeSet<>(a.metrics.keySet())) {
            sb.append("<option value=\"").append(esc(m)).append("\">").append(esc(m)).append("</option>");
        }
        sb.append("</select><select id=\"so\" aria-label=\"Sort\"><option value=\"orig\">Failures first</option>")
                .append("<option value=\"asc\">Score ↑</option><option value=\"desc\">Score ↓</option>")
                .append("<option value=\"gap\">Closest to threshold</option><option value=\"slow\">Slowest</option>")
                .append("</select><button id=\"open-all\" type=\"button\">Expand</button>")
                .append("<button id=\"close-all\" type=\"button\">Collapse</button>")
                .append("<button id=\"csv\" type=\"button\">Export CSV</button><span id=\"count\" class=\"count\">")
                .append("</span></div><div id=\"evlist\">");

        // Failures first, then passes, each in original order; ids stay the original index.
        List<Integer> order = new ArrayList<>(a.total);
        for (int i = 0; i < a.total; i++) {
            if (!a.records.get(i).passed()) {
                order.add(i);
            }
        }
        int failures = order.size();
        for (int i = 0; i < a.total; i++) {
            if (a.records.get(i).passed()) {
                order.add(i);
            }
        }
        Map<Integer, ReportAnalysis.CaseChange> changeByIndex = new java.util.HashMap<>();
        for (List<ReportAnalysis.CaseChange> list :
                List.of(a.newFailures, a.fixed, a.worse, a.better)) {
            for (ReportAnalysis.CaseChange c : list) {
                changeByIndex.put(c.recordIndex(), c);
            }
        }
        for (int idx : order) {
            evaluation(sb, a, idx, failures <= AUTO_OPEN_FAILURES, changeByIndex.get(idx));
        }
        sb.append("</div>");
    }

    private static void evaluation(
            StringBuilder sb,
            ReportAnalysis a,
            int idx,
            boolean openFailures,
            ReportAnalysis.CaseChange change) {
        EvalRecord r = a.records.get(idx);
        String status = r.passed() ? "pass" : "fail";
        sb.append("<details class=\"ev ")
                .append(status)
                .append("\" id=\"e")
                .append(idx)
                .append("\" data-status=\"")
                .append(status)
                .append("\" data-metric=\"")
                .append(esc(r.metric()))
                .append("\" data-suite=\"")
                .append(esc(r.suite()))
                .append("\" data-test=\"")
                .append(esc(r.testName()))
                .append("\" data-score=\"")
                .append(String.format(Locale.ROOT, "%.4f", r.score()))
                .append("\" data-threshold=\"")
                .append(String.format(Locale.ROOT, "%.4f", r.threshold()))
                .append("\" data-gap=\"")
                .append(String.format(Locale.ROOT, "%.4f", Math.abs(r.score() - r.threshold())))
                .append("\" data-ms=\"")
                .append(r.durationMs() == null ? 0 : r.durationMs())
                .append("\" data-reason=\"")
                .append(esc(r.reason()))
                .append('"')
                .append(!r.passed() && openFailures ? " open" : "")
                .append("><summary><span class=\"chip ")
                .append(status)
                .append("\">")
                .append(r.passed() ? "PASS" : "FAIL")
                .append("</span><span class=\"t\">")
                .append(esc(r.testName() == null ? "(outside a test)" : r.testName()))
                .append(r.suite() == null ? "" : " <small>" + esc(simpleName(r.suite())) + "</small>")
                .append("</span><span class=\"m\">")
                .append(esc(r.metric()))
                .append("</span><span class=\"sc\">")
                .append(Charts.scoreBar(r.score(), r.threshold()))
                .append(" <span class=\"num\">")
                .append(String.format(Locale.ROOT, "%.3f", r.score()))
                .append("</span> <small class=\"thr flat\">≥ ")
                .append(String.format(Locale.ROOT, "%.2f", r.threshold()))
                .append("</small></span></summary><div class=\"body\">");

        sb.append("<div class=\"blk reason\"><h4>")
                .append(r.passed() ? "Judge reasoning" : "Why it failed")
                .append("</h4><p>")
                .append(esc(r.reason() == null || r.reason().isBlank() ? "(no reason recorded)" : r.reason()))
                .append("</p></div>");
        block(sb, "Input", r.input());
        block(sb, "Actual output", r.actualOutput());
        block(sb, "Expected output", r.expectedOutput());
        if (r.retrievalContext() != null && !r.retrievalContext().isEmpty()) {
            sb.append("<div class=\"blk\"><h4>Retrieved context (")
                    .append(r.retrievalContext().size())
                    .append(")</h4><ol>");
            for (String chunk : r.retrievalContext()) {
                sb.append("<li><pre>").append(esc(chunk)).append("</pre></li>");
            }
            sb.append("</ol></div>");
        }
        sb.append("<div class=\"facts\">");
        fact(sb, "judge", r.judgeIdentifier());
        fact(sb, "recorded", r.timestamp());
        fact(sb, "judge time", r.durationMs() == null ? null : seconds(r.durationMs()));
        if (change != null) {
            fact(
                    sb,
                    "previous run",
                    String.format(Locale.ROOT, "%.3f (%+.3f)", change.previous(), change.delta()));
        }
        sb.append("</div></div></details>");
    }

    private static void block(StringBuilder sb, String title, String text) {
        if (text == null || text.isBlank()) {
            return;
        }
        sb.append("<div class=\"blk\"><h4>")
                .append(esc(title))
                .append("</h4><pre>")
                .append(esc(text))
                .append("</pre></div>");
    }

    private static void fact(StringBuilder sb, String label, String value) {
        if (value != null && !value.isBlank()) {
            sb.append("<span>").append(esc(label)).append(": ").append(esc(value)).append("</span>");
        }
    }

    // --- tests -----------------------------------------------------------------------------

    private static void tests(StringBuilder sb, ReportAnalysis a) {
        List<TestOutcome> tests = a.run.tests();
        if (tests == null || tests.isEmpty()) {
            return;
        }
        sb.append("<h2 id=\"tests\">Tests <small>JUnit outcomes, failures first</small></h2>")
                .append("<div class=\"panel\"><table class=\"sortable\"><thead><tr><th>Result</th>")
                .append("<th>Suite</th><th>Test</th><th>Time</th><th>Message</th></tr></thead><tbody>");
        List<TestOutcome> sorted = new ArrayList<>(tests);
        sorted.sort(Comparator.comparing(TestOutcome::passed));
        for (TestOutcome t : sorted) {
            sb.append("<tr><td><span class=\"chip ")
                    .append(t.passed() ? "pass" : "fail")
                    .append("\">")
                    .append(esc(t.status()))
                    .append("</span></td><td>")
                    .append(esc(simpleName(t.suite())))
                    .append("</td><td>")
                    .append(esc(t.testName()))
                    .append("</td><td class=\"num\">")
                    .append(seconds(t.durationMs()))
                    .append("</td><td class=\"wrap-ok\">")
                    .append(esc(t.message()))
                    .append("</td></tr>");
        }
        sb.append("</tbody></table></div>");
    }

    // --- naming ----------------------------------------------------------------------------

    static String simpleName(String suite) {
        if (suite == null) {
            return "";
        }
        int dot = suite.lastIndexOf('.');
        return dot >= 0 ? suite.substring(dot + 1) : suite;
    }

    private static String shortTest(EvalRecord r) {
        return shortName(r.suite(), r.testName());
    }

    private static String shortName(String suite, String test) {
        String t = test == null ? "(outside a test)" : test;
        return suite == null ? t : simpleName(suite) + " · " + t;
    }
}

package io.github.llm4j.loom.generate;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * R7 to R9, R27, R28, R30: the files in a temporary project, laid out and stamped, moved only when
 * asked.
 */
class WriterTest {

    @TempDir Path dir;

    static final Writer.Stamp STAMP = new Writer.Stamp("weave generate 6.1.0", "2026-10-23");

    private Workspace render(Writer.Layout layout) throws Exception {
        Map<String, String> files = new LinkedHashMap<>(GenerateFixtures.files());
        files.putAll(Writer.datasetStub(GenerateFixtures.plan()));
        return Writer.render(files, GenerateFixtures.plan(), layout, STAMP, dir);
    }

    @Test
    void aFlatProjectKeepsEverythingBesideTheScript() throws Exception {
        try (Workspace ws = render(Writer.Layout.FLAT)) {
            assertThat(ws.files())
                    .contains(
                            "main.loom", "prompts/drafter.md", "prompts/notifier.md", "README.md");
            assertThat(ws.script()).isEqualTo(ws.dir().resolve("main.loom"));
            assertThat(Files.exists(ws.dir().resolve("pom.xml"))).isFalse();
        }
    }

    @Test
    void aMavenProjectPutsTheScriptAndPromptsInResourcesAndAddsThePom() throws Exception {
        try (Workspace ws = render(Writer.Layout.MAVEN)) {
            assertThat(ws.files())
                    .contains(
                            "src/main/resources/main.loom",
                            "src/main/resources/prompts/drafter.md",
                            "pom.xml");
            assertThat(ws.script()).isEqualTo(ws.dir().resolve("src/main/resources/main.loom"));
            assertThat(Files.readString(ws.dir().resolve("pom.xml")))
                    .contains("<artifactId>support-notify</artifactId>");
            assertThat(Files.exists(ws.dir().resolve(".gitignore"))).isTrue();
        }
    }

    @Test
    void everyFileSaysWhatMadeItAndFromWhichPlanAndNeverWhichModel() throws Exception {
        try (Workspace ws = render(Writer.Layout.FLAT)) {
            String script = Files.readString(ws.script());
            String hash = PlanJson.hash(GenerateFixtures.plan());
            assertThat(script)
                    .startsWith(
                            "// Generated by weave generate 6.1.0 on 2026-10-23 from plan "
                                    + hash
                                    + ".\n");
            assertThat(Files.readString(ws.dir().resolve("prompts/drafter.md")))
                    .startsWith("<!-- Generated by weave generate");
            // the model named in the plan is a setting of the workflow; the header does not name
            // any
            assertThat(script.lines().findFirst().orElse(""))
                    .doesNotContain("claude")
                    .doesNotContain("haiku");
        }
    }

    @Test
    void aTargetMustBeEmptyOrAbsentAndNothingIsEverReplaced() throws Exception {
        Path target = dir.resolve("out");
        try (Workspace ws = render(Writer.Layout.FLAT)) {
            var done = ws.commit(target, false);
            assertThat(done.ok()).isTrue();
            assertThat(Files.exists(target.resolve("main.loom"))).isTrue();
        }
        try (Workspace again = render(Writer.Layout.FLAT)) {
            var refused = again.commit(target, false);
            assertThat(refused.ok()).isFalse();
            assertThat(refused.conflicts().get(0)).contains("not empty");
            var existing = again.commit(target, true);
            assertThat(existing.conflicts()).contains("main.loom");
            assertThat(existing.written()).isEmpty();
        }
    }

    @Test
    void intoExistingAddsOnlyWhatIsNotThere() throws Exception {
        Path target = Files.createDirectory(dir.resolve("mine"));
        Files.writeString(target.resolve("notes.txt"), "mine");
        try (Workspace ws = render(Writer.Layout.FLAT)) {
            var done = ws.commit(target, true);
            assertThat(done.ok()).isTrue();
            assertThat(Files.readString(target.resolve("notes.txt"))).isEqualTo("mine");
        }
    }

    @Test
    void theTemporaryProjectIsRemovedWhenClosed() throws Exception {
        Path where;
        try (Workspace ws = render(Writer.Layout.FLAT)) {
            where = ws.dir();
            assertThat(Files.exists(where)).isTrue();
        }
        assertThat(Files.exists(where)).isFalse();
    }

    @Test
    void pathsThatEscapeOrAreNotProjectFilesAreRefused() {
        for (String bad :
                new String[] {
                    "../x.loom",
                    "/etc/passwd",
                    "prompts/../../x.md",
                    ".env",
                    "src/Main.java",
                    "prompts/Upper.md",
                    "C:/x.loom"
                }) assertThat(Writer.problemWith(bad)).as(bad).isNotNull();
        for (String ok :
                new String[] {
                    "main.loom",
                    "tools.loot",
                    "prompts/a-b_c.md",
                    "tests/main.test.yaml",
                    "eval/golden/dataset.yaml"
                }) assertThat(Writer.problemWith(ok)).as(ok).isNull();
    }

    @Test
    void aFileThatIsTooBigOrHoldsAKeyIsRefusedBeforeAnythingIsWritten() {
        Map<String, String> files = new LinkedHashMap<>(GenerateFixtures.files());
        files.put(
                "prompts/notifier.md",
                "Use the key sk-abcdefghijklmnopqrstuvwxyz0123456789 to send.");
        files.put("README.md", "x".repeat((int) Writer.MAX_FILE_BYTES + 1));
        assertThat(Writer.problems(files))
                .anyMatch(s -> s.contains("prompts/notifier.md") && s.contains("shaped like a key"))
                .anyMatch(s -> s.contains("README.md") && s.contains("larger than"));
        assertThatThrownBy(
                        () ->
                                Writer.render(
                                        files,
                                        GenerateFixtures.plan(),
                                        Writer.Layout.FLAT,
                                        STAMP,
                                        dir))
                .isInstanceOf(IllegalArgumentException.class);
        assertThat(dir.toFile().list()).isEmpty();
    }

    @Test
    void anEscapingPathInTheModelsFilesNeverTouchesTheDisk() throws Exception {
        Map<String, String> files = new LinkedHashMap<>(GenerateFixtures.files());
        files.put("../evil.loom", "x");
        assertThatThrownBy(
                        () ->
                                Writer.render(
                                        files,
                                        GenerateFixtures.plan(),
                                        Writer.Layout.FLAT,
                                        STAMP,
                                        dir))
                .hasMessageContaining("leaves the project folder");
        assertThat(Files.exists(dir.resolveSibling("evil.loom"))).isFalse();
    }
}

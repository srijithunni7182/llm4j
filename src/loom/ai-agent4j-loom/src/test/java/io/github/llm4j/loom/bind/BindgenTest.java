package io.github.llm4j.loom.bind;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import io.github.llm4j.LLMClient;
import io.github.llm4j.loom.execution.LoomLoader;
import io.github.llm4j.loom.execution.ToolRegistry;
import io.github.llm4j.loom.host.LoomHost;
import io.github.llm4j.model.LLMRequest;
import io.github.llm4j.model.LLMResponse;
import java.io.StringWriter;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;
import javax.tools.JavaCompiler;
import javax.tools.ToolProvider;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** R1 to R7, R12 of spec 15: typed bindings that compile cleanly, are deterministic and run. */
public class BindgenTest {

    @TempDir Path dir;

    public static final String SCRIPT =
            """
            agent Writer { model: "test/model" system: "You write." }
            intentclassifier Intent {
                model: "test/model"
                choose kind: order_status | "refund-request"
                ask urgent: "Is the customer angry?"
                confidence at least 0.8 else escalate
            }
            workflow Main(ticket_body, class) {
                intentclassify Intent on ticket_body -> intent
                alt (intent.kind == "refund-request") {
                    delegate "write about {ticket_body}" to Writer -> out
                    return { team: "refunds", kind: intent.kind, urgent: intent.urgent, answer: out, score: 2, ok: true }
                } else {
                    return { team: "general", kind: intent.kind }
                }
            }
            workflow Echo(x) {
                delegate "say {x}" to Writer -> said
                return said
            }
            workflow Quiet() {
                set done = "yes"
            }
            """;

    private Path script(String text) throws Exception {
        Path p = dir.resolve("triage.loom");
        Files.writeString(p, text);
        return p;
    }

    private Bindgen.Generated generate(Bindgen.Nullability n) throws Exception {
        return Bindgen.generate(script(SCRIPT), "com.acme.triage", null, n);
    }

    private ClassLoader compile(Bindgen.Generated g, Path out) throws Exception {
        Files.createDirectories(out);
        List<String> args =
                new java.util.ArrayList<>(
                        List.of(
                                "-Xlint:all",
                                "-Werror",
                                "-d",
                                out.toString(),
                                "-cp",
                                System.getProperty("java.class.path"),
                                "--release",
                                "17"));
        for (var f : g.files().entrySet()) {
            Path src = dir.resolve("src").resolve(f.getKey());
            Files.createDirectories(src.getParent());
            Files.writeString(src, f.getValue());
            args.add(src.toString());
        }
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        StringWriter err = new StringWriter();
        int rc =
                javac.run(
                        null,
                        null,
                        new java.io.PrintStream(new java.io.ByteArrayOutputStream()) {
                            @Override
                            public void write(byte[] b, int o, int l) {
                                err.write(new String(b, o, l));
                            }
                        },
                        args.toArray(String[]::new));
        assertThat(rc).as(err.toString()).isZero();
        return new URLClassLoader(new URL[] {out.toUri().toURL()}, getClass().getClassLoader());
    }

    @Test
    void theGeneratedCodeCompilesWithNoWarningsAndNoDependencyButLoom() throws Exception {
        compile(generate(Bindgen.Nullability.NONE), dir.resolve("o1"));
        compile(generate(Bindgen.Nullability.OPTIONAL), dir.resolve("o2"));
    }

    @Test
    void sameScriptSameBytesAndTheHeaderSaysWhereItCameFrom() throws Exception {
        Bindgen.Generated a = generate(Bindgen.Nullability.NONE);
        Bindgen.Generated b = generate(Bindgen.Nullability.NONE);
        assertThat(a.files()).isEqualTo(b.files());
        assertThat(a.files().keySet())
                .containsExactly(
                        "com/acme/triage/Outcome.java", "com/acme/triage/TriageWorkflows.java");
        String facade = a.files().get("com/acme/triage/TriageWorkflows.java");
        assertThat(facade)
                .startsWith("// Generated by weave bindgen 1 from triage.loom (sha256 ")
                .contains("Do not edit");
        assertThat(facade).doesNotContain("Instant.now").doesNotContain("LocalDate");
    }

    @Test
    void namesAreTheScriptsNamesAndTheResultIsTheUnionOfTheReturns() throws Exception {
        String f =
                generate(Bindgen.Nullability.NONE)
                        .files()
                        .get("com/acme/triage/TriageWorkflows.java");
        assertThat(f)
                .contains("Outcome<MainResult> main(String ticketBody, String class_)")
                .contains("MainCall mainCall();")
                .contains("Outcome<EchoResult> echo(String x)")
                .contains("Outcome<QuietResult> quiet()")
                .contains(
                        "record MainResult(String team, IntentKind kind, IntentUrgent urgent, String answer, Double score, Boolean ok)")
                .contains("record EchoResult(String result)")
                .contains("record QuietResult()");
        // choices are enums, with UNSURE since the classifier escalates
        assertThat(f)
                .contains("enum IntentKind")
                .contains("ORDER_STATUS(\"order_status\")")
                .contains("REFUND_REQUEST(\"refund-request\")")
                .contains("UNSURE(\"unsure\")");
        assertThat(f).contains("enum IntentUrgent").contains("YES(\"yes\")").contains("NO(\"no\")");
    }

    @Test
    void aFieldNotSetOnEveryPathIsShownAccordingToTheNullabilityChoice() throws Exception {
        assertThat(
                        generate(Bindgen.Nullability.OPTIONAL)
                                .files()
                                .get("com/acme/triage/TriageWorkflows.java"))
                .contains("Optional<IntentUrgent> urgent")
                .contains("IntentKind kind")
                .contains("Optional<Boolean> ok");
        assertThat(
                        generate(Bindgen.Nullability.JSPECIFY)
                                .files()
                                .get("com/acme/triage/TriageWorkflows.java"))
                .contains("@org.jspecify.annotations.Nullable IntentUrgent urgent");
    }

    @Test
    void aWorkflowWithNoObjectReturnSaysSoInTheNotes() throws Exception {
        assertThat(generate(Bindgen.Nullability.NONE).notes())
                .anyMatch(n -> n.contains("workflow Quiet returns no object"));
    }

    @Test
    void aPackageThatIsNotAPackageIsRefused() throws Exception {
        assertThatThrownBy(
                        () ->
                                Bindgen.generate(
                                        script(SCRIPT), "Com.Acme", null, Bindgen.Nullability.NONE))
                .hasMessageContaining("--package");
    }

    @Test
    void theFacadeRunsAWorkflowAndHandsBackTypedValues() throws Exception {
        Path s = script(SCRIPT);
        Bindgen.Generated g =
                Bindgen.generate(s, "com.acme.triage", null, Bindgen.Nullability.NONE);
        ClassLoader cl = compile(g, dir.resolve("run"));
        LoomHost host =
                LoomHost.builder(
                                new LoomLoader().load(s.toString()),
                                new ToolRegistry(),
                                model ->
                                        new LLMClient() {
                                            @Override
                                            public LLMResponse chat(LLMRequest r) {
                                                return LLMResponse.builder()
                                                        .content(
                                                                "```json\n{\"thought\": \"t\", \"final_answer\": \"hello there\"}\n```")
                                                        .model(model)
                                                        .tokenUsage(10, 5, 15)
                                                        .build();
                                            }

                                            @Override
                                            public Stream<LLMResponse> chatStream(LLMRequest r) {
                                                return Stream.of(chat(r));
                                            }
                                        })
                        .baseDir(dir)
                        .scriptRef(s.toAbsolutePath().toString())
                        .build();
        Class<?> facade = cl.loadClass("com.acme.triage.TriageWorkflows");
        Object wf = facade.getMethod("of", LoomHost.class).invoke(null, host);
        Object outcome = facade.getMethod("echo", String.class).invoke(wf, "hi");
        Class<?> done = cl.loadClass("com.acme.triage.Outcome$Done");
        assertThat(outcome).isInstanceOf(done);
        Object value = done.getMethod("value").invoke(outcome);
        assertThat(value.toString()).contains("hello there");
        assertThat(((Map<?, ?>) done.getMethod("variables").invoke(outcome)).containsKey("result"))
                .isTrue();
        Object orElse =
                cl.loadClass("com.acme.triage.Outcome").getMethod("orElseThrow").invoke(outcome);
        assertThat(orElse).isEqualTo(value);
    }
}

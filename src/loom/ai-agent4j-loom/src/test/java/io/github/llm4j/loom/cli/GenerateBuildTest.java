    @TempDir Path dir;

    static Map<String, String> modelFiles() {
        Map<String, String> f = new LinkedHashMap<>(GenerateFixtures.files());
        return f;
    }

    private static String files(Map<String, String> f) {
        return "Here you are.\n" + FileBlocks.render(f);
    }

    private GenerateCommandTest.Out run(
            String interview, String plan, String[] writes, String... args) {
        String[] replies = new String[2 + writes.length];
        replies[0] = interview;
        replies[1] = plan;
        System.arraycopy(writes, 0, replies, 2, writes.length);
        String[] all = new String[args.length + 3];
        all[0] = "make a support notifier";
        all[1] = "--model";
        all[2] = "m";
        System.arraycopy(args, 0, all, 3, args.length);
        return GenerateCommandTest.generate(GenerateCommandTest.sequence(replies), all);
    }

    @Test
    void aDescriptionBecomesAProjectThatPassesTheGates() throws Exception {
        Path out = dir.resolve("made");
        var o =
                run(
                        "[]",
                        PlanJson.write(GenerateFixtures.plan()),
                        new String[] {files(modelFiles())},
                        "--out",
                        out.toString(),
                        "--flat",
                        "--no-ask");
        // the only thing said on standard error is that money cannot be counted without prices
        assertThat(o.err()).startsWith("Note: no price is known for m").doesNotContain("Error");
        assertThat(o.out())
                .as(o.out())
                .contains("✓ Made SupportNotify")
                .contains("✓ G1 check")
                .contains("✓ G2 review")
                .contains("✓ G5 plan")
                .contains("Not checked:")
                .contains("Next");
        assertThat(o.code()).isZero();
        assertThat(Files.readString(out.resolve("main.loom")))
                .startsWith("// Generated by weave generate");
        assertThat(Files.exists(out.resolve("plan.json"))).isTrue();
        assertThat(Files.exists(out.resolve("PLAN.md"))).isTrue();
        assertThat(Files.exists(out.resolve("eval/golden/dataset.yaml"))).isTrue();
        // and the same gates say so on the result
        assertThat(
                        GenerateCommandTest.generate(
                                        GenerateCommandTest.noModels(),
                                        "--gate-only",
                                        out.toString())
                                .code())
                .isZero();
    }


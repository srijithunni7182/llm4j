package io.github.llm4j.loom.bind;

import io.github.llm4j.loom.ast.LoomScript;
import io.github.llm4j.loom.ast.WorkflowDef;
import io.github.llm4j.loom.execution.LoomLoader;
import io.github.llm4j.loom.travel.ScriptHash;
import java.io.IOException;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Typed Java bindings for a script: a facade with one method per workflow, a record for each
 * workflow's result, an enum for each classifier question a result carries, and a sealed {@code
 * Outcome} that makes waiting for a person explicit. A pure function of the script: the same script
 * gives byte-identical files, and nothing is loaded, called or read beyond the script.
 */
public final class Bindgen {

    private Bindgen() {}

    public static final String VERSION = "1";

    /** The Java method name bindings give a workflow, so other readers of a script agree. */
    public static String methodName(String workflow) {
        return Naming.member(workflow);
    }

    public enum Nullability {
        NONE,
        JSPECIFY,
        OPTIONAL
    }

    /** The files to write, by path relative to the output directory, in a fixed order. */
    public record Generated(Map<String, String> files, List<String> notes) {}

    public static Generated generate(
            Path scriptFile, String pkg, String facade, Nullability nullability)
            throws IOException {
        if (!pkg.matches("[a-z_][a-z0-9_]*(\\.[a-z_][a-z0-9_]*)*"))
            throw new IllegalArgumentException(
                    "--package is a Java package like com.acme.triage, not " + pkg);
        LoomScript script = new LoomLoader().load(scriptFile.toString());
        String hash = ScriptHash.of(scriptFile).substring(0, 16);
        String name =
                facade != null && !facade.isBlank()
                        ? facade
                        : Naming.type(stem(scriptFile)) + "Workflows";
        List<String> notes = new ArrayList<>();
        String dir = pkg.replace('.', '/') + "/";
        Map<String, String> files = new LinkedHashMap<>();
        files.put(dir + "Outcome.java", outcome(pkg));
        files.put(
                dir + name + ".java",
                facade(
                        script,
                        scriptFile.getFileName().toString(),
                        hash,
                        pkg,
                        name,
                        nullability,
                        notes));
        return new Generated(files, notes);
    }

    private static String stem(Path p) {
        String n = p.getFileName().toString();
        int dot = n.lastIndexOf('.');
        return dot > 0 ? n.substring(0, dot) : n;
    }

    private static String header(String source, String hash) {
        return "// Generated by weave bindgen "
                + VERSION
                + " from "
                + source
                + " (sha256 "
                + hash
                + "). Do not edit; regenerate with weave bindgen.\n";
    }

    // ---- Outcome

    private static String outcome(String pkg) {
        return header("the workflow scripts", "-")
                + "package "
                + pkg
                + ";\n\n"
                + """
                import io.github.llm4j.loom.runtime.RunSuspended;
                import java.time.Instant;
                import java.util.Map;

                /** How a run ended: done, waiting for a person or a time (holding no thread), or stopped. A failure is thrown, as by the host. */
                public sealed interface Outcome<T> {

                    String runId();

                    /** The workflow finished; {@code value} is what it returned and {@code variables} everything it computed. */
                    record Done<T>(String runId, T value, Map<String, Object> variables) implements Outcome<T> {}

                    /** The run is suspended; {@code resumeAt} is null while it waits for a person, whose question is {@code prompt}. */
                    record Waiting<T>(String runId, RunSuspended.Reason reason, Instant resumeAt, String stepId, String prompt) implements Outcome<T> {}

                    /** An operator or the application stopped the run at a safe point; resuming carries on. */
                    record Stopped<T>(String runId, String detail) implements Outcome<T> {}

                    /** The value when done; otherwise an IllegalStateException saying how it ended. */
                    default T orElseThrow() {
                        if (this instanceof Done<T> d) return d.value();
                        if (this instanceof Waiting<T> w) throw new IllegalStateException("run " + w.runId() + " is waiting: " + (w.prompt() != null ? w.prompt() : w.reason()));
                        throw new IllegalStateException("run " + runId() + " was stopped: " + ((Stopped<T>) this).detail());
                    }
                }
                """;
    }

    // ---- the facade

    private static String facade(
            LoomScript script,
            String source,
            String hash,
            String pkg,
            String name,
            Nullability nullability,
            List<String> notes) {
        List<WorkflowDef> workflows = script.getWorkflows();
        Map<String, SchemaInfer.Type> enums = new LinkedHashMap<>();
        Map<String, SchemaInfer.Shape> shapes = new LinkedHashMap<>();
        for (WorkflowDef w : workflows) {
            SchemaInfer.Shape s = SchemaInfer.infer(script, w);
            shapes.put(w.getName(), s);
            for (SchemaInfer.Field f : s.fields())
                if (f.type().kind() == SchemaInfer.Type.Kind.ENUM)
                    enums.putIfAbsent(f.type().enumName(), f.type());
            if (!s.hasObject() && s.single() == null)
                notes.add(
                        "workflow "
                                + w.getName()
                                + " returns no object: its result record is empty; read the final context with variables()");
        }
        StringBuilder b = new StringBuilder(header(source, hash));
        b.append("package ").append(pkg).append(";\n\n");
        b.append("import io.github.llm4j.loom.host.AnswerResult;\n");
        b.append("import io.github.llm4j.loom.host.LoomHost;\n");
        b.append("import io.github.llm4j.loom.host.RunOutcome;\n");
        b.append("import io.github.llm4j.loom.host.RunRequest;\n");
        b.append("import io.github.llm4j.secret.InvokerCredentials;\n");
        b.append("import java.util.LinkedHashMap;\nimport java.util.Map;\n");
        if (nullability == Nullability.OPTIONAL) b.append("import java.util.Optional;\n");
        b.append("\n/** The workflows of ").append(source).append(", typed. */\n");
        b.append("public interface ").append(name).append(" {\n\n");

        for (WorkflowDef w : workflows) {
            String m = Naming.member(w.getName());
            String t = Naming.type(w.getName());
            b.append("    /** workflow ")
                    .append(w.getName())
                    .append(" (")
                    .append(source)
                    .append(':')
                    .append(w.getLine())
                    .append(") */\n");
            b.append("    Outcome<").append(t).append("Result> ").append(m).append('(');
            b.append(params(w, true)).append(");\n\n");
            b.append(
                    "    /** The same with options: run id, label, origin, invoker credentials. */\n");
            b.append("    ").append(t).append("Call ").append(m).append("Call();\n\n");
            b.append("    /** Carries on a suspended ").append(w.getName()).append(" run. */\n");
            b.append("    Outcome<")
                    .append(t)
                    .append("Result> resume")
                    .append(t)
                    .append("(String runId);\n\n");
        }
        b.append("    /** Gives a run waiting for a person its answer. */\n");
        b.append(
                "    AnswerResult answer(String runId, String stepId, String text, String by);\n\n");
        b.append("    static ").append(name).append(" of(LoomHost host) {\n");
        b.append("        return new Impl(host);\n    }\n\n");

        for (var e : enums.values()) enumSource(b, e);
        for (WorkflowDef w : workflows)
            recordSource(b, Naming.type(w.getName()), shapes.get(w.getName()), nullability);
        for (WorkflowDef w : workflows) callSource(b, w, name);
        implSource(b, name, workflows, shapes, nullability);
        b.append("}\n");
        return b.toString();
    }

    private static String params(WorkflowDef w, boolean types) {
        List<String> out = new ArrayList<>();
        for (String p : w.getParameters()) out.add((types ? "String " : "") + Naming.member(p));
        return String.join(", ", out);
    }

    private static void enumSource(StringBuilder b, SchemaInfer.Type e) {
        b.append(
                "    /** A choice of the classifier; UNSURE is what the runtime produces when it is not sure. */\n");
        b.append("    enum ").append(e.enumName()).append(" {\n");
        List<String> consts = new ArrayList<>();
        for (String l : e.labels()) consts.add("        " + Naming.constant(l) + "(\"" + l + "\")");
        b.append(String.join(",\n", consts)).append(";\n\n");
        b.append("        private final String label;\n\n");
        b.append("        ")
                .append(e.enumName())
                .append("(String label) {\n            this.label = label;\n        }\n\n");
        b.append("        public String label() {\n            return label;\n        }\n\n");
        b.append("        static ").append(e.enumName()).append(" of(String label) {\n");
        b.append("            if (label == null) return null;\n");
        b.append("            for (").append(e.enumName()).append(" v : values())\n");
        b.append("                if (v.label.equalsIgnoreCase(label)) return v;\n");
        b.append(
                        "            throw new IllegalStateException(\"the workflow answered '\" + label + \"', which ")
                .append(e.enumName())
                .append(" does not have; regenerate the bindings\");\n");
        b.append("        }\n    }\n\n");
    }

    private static String javaType(SchemaInfer.Type t) {
        return switch (t.kind()) {
            case TEXT -> "String";
            case NUMBER -> "Double";
            case BOOL -> "Boolean";
            case ENUM -> t.enumName();
        };
    }

    private static void recordSource(
            StringBuilder b, String t, SchemaInfer.Shape s, Nullability nullability) {
        List<SchemaInfer.Field> fields = s.fields();
        b.append("    /** What ").append(t).append(" returns");
        if (s.returns() > 1)
            b.append(" (")
                    .append(s.returns())
                    .append(" return statements; a field not set on every path is nullable)");
        b.append(". */\n");
        List<String> comps = new ArrayList<>();
        if (fields.isEmpty() && s.single() != null) comps.add(javaType(s.single()) + " result");
        for (SchemaInfer.Field f : fields) {
            String type = javaType(f.type());
            String c;
            if (f.nullable() && nullability == Nullability.OPTIONAL)
                c = "Optional<" + type + "> " + Naming.member(f.name());
            else if (f.nullable() && nullability == Nullability.JSPECIFY)
                c = "@org.jspecify.annotations.Nullable " + type + " " + Naming.member(f.name());
            else c = type + " " + Naming.member(f.name());
            comps.add(c);
        }
        b.append("    record ")
                .append(t)
                .append("Result(")
                .append(String.join(", ", comps))
                .append(") {}\n\n");
    }

    private static void callSource(StringBuilder b, WorkflowDef w, String facade) {
        String t = Naming.type(w.getName());
        b.append("    /** A call of ").append(w.getName()).append(" with options. */\n");
        b.append("    final class ").append(t).append("Call {\n");
        b.append("        private final Map<String, String> inputs = new LinkedHashMap<>();\n");
        b.append(
                "        private String runId;\n        private String label;\n        private String origin;\n        private InvokerCredentials invoker;\n");
        b.append("        private final java.util.function.Function<RunRequest, Outcome<")
                .append(t)
                .append("Result>> runner;\n\n");
        b.append("        ")
                .append(t)
                .append("Call(java.util.function.Function<RunRequest, Outcome<")
                .append(t)
                .append("Result>> runner) {\n            this.runner = runner;\n        }\n\n");
        for (String p : w.getParameters()) {
            String m = Naming.member(p);
            b.append("        public ")
                    .append(t)
                    .append("Call ")
                    .append(m)
                    .append("(String value) {\n");
            b.append("            if (value != null) inputs.put(\"")
                    .append(p)
                    .append("\", value);\n            return this;\n        }\n\n");
        }
        b.append("        public ")
                .append(t)
                .append(
                        "Call runId(String id) {\n            this.runId = id;\n            return this;\n        }\n\n");
        b.append("        public ")
                .append(t)
                .append(
                        "Call label(String text) {\n            this.label = text;\n            return this;\n        }\n\n");
        b.append("        public ")
                .append(t)
                .append(
                        "Call origin(String who) {\n            this.origin = who;\n            return this;\n        }\n\n");
        b.append("        public ")
                .append(t)
                .append(
                        "Call invoker(InvokerCredentials credentials) {\n            this.invoker = credentials;\n            return this;\n        }\n\n");
        b.append("        public Outcome<").append(t).append("Result> run() {\n");
        b.append("            return runner.apply(new RunRequest(\"")
                .append(w.getName())
                .append("\", inputs, runId, label, origin, invoker));\n        }\n    }\n\n");
    }

    private static void implSource(
            StringBuilder b,
            String facade,
            List<WorkflowDef> workflows,
            Map<String, SchemaInfer.Shape> shapes,
            Nullability nullability) {
        b.append("    final class Impl implements ").append(facade).append(" {\n");
        b.append("        private final LoomHost host;\n\n");
        b.append(
                "        Impl(LoomHost host) {\n            this.host = java.util.Objects.requireNonNull(host, \"host\");\n        }\n\n");
        for (WorkflowDef w : workflows) {
            String m = Naming.member(w.getName());
            String t = Naming.type(w.getName());
            b.append("        @Override\n        public Outcome<")
                    .append(t)
                    .append("Result> ")
                    .append(m)
                    .append('(')
                    .append(params(w, true))
                    .append(") {\n");
            b.append("            return ").append(m).append("Call()");
            for (String p : w.getParameters())
                b.append('.')
                        .append(Naming.member(p))
                        .append('(')
                        .append(Naming.member(p))
                        .append(')');
            b.append(".run();\n        }\n\n");
            b.append("        @Override\n        public ")
                    .append(t)
                    .append("Call ")
                    .append(m)
                    .append("Call() {\n");
            b.append("            return new ")
                    .append(t)
                    .append("Call(request -> wrap")
                    .append(t)
                    .append("(host.run(request)));\n        }\n\n");
            b.append("        @Override\n        public Outcome<")
                    .append(t)
                    .append("Result> resume")
                    .append(t)
                    .append("(String runId) {\n");
            b.append("            return wrap")
                    .append(t)
                    .append("(host.resume(runId, null));\n        }\n\n");
        }
        b.append(
                "        @Override\n        public AnswerResult answer(String runId, String stepId, String text, String by) {\n            return host.answer(runId, stepId, text, by);\n        }\n\n");
        for (WorkflowDef w : workflows) wrapSource(b, w, shapes.get(w.getName()), nullability);
        b.append(HELPERS);
        b.append("    }\n");
    }

    private static void wrapSource(
            StringBuilder b, WorkflowDef w, SchemaInfer.Shape s, Nullability nullability) {
        String t = Naming.type(w.getName());
        b.append("        private static Outcome<")
                .append(t)
                .append("Result> wrap")
                .append(t)
                .append("(RunOutcome o) {\n");
        b.append(
                        "            if (o instanceof RunOutcome.Completed c) return new Outcome.Done<>(c.runId(), map")
                .append(t)
                .append("(c.variables().get(\"result\")), c.variables());\n");
        b.append(
                "            if (o instanceof RunOutcome.Suspended s) return new Outcome.Waiting<>(s.runId(), s.reason(), s.resumeAt(), s.stepId(), s.prompt());\n");
        b.append(
                "            RunOutcome.Stopped st = (RunOutcome.Stopped) o;\n            return new Outcome.Stopped<>(st.runId(), st.detail());\n        }\n\n");
        b.append("        private static ")
                .append(t)
                .append("Result map")
                .append(t)
                .append("(Object result) {\n");
        if (s.fields().isEmpty() && s.single() != null) {
            b.append("            return new ")
                    .append(t)
                    .append("Result(")
                    .append(convert(s.single(), "result"))
                    .append(");\n        }\n\n");
            return;
        }
        if (s.fields().isEmpty()) {
            b.append("            return new ").append(t).append("Result();\n        }\n\n");
            return;
        }
        b.append("            Map<?, ?> m = result instanceof Map<?, ?> x ? x : Map.of();\n");
        List<String> args = new ArrayList<>();
        for (SchemaInfer.Field f : s.fields()) {
            String v = convert(f.type(), "m.get(\"" + f.name() + "\")");
            args.add(
                    f.nullable() && nullability == Nullability.OPTIONAL
                            ? "Optional.ofNullable(" + v + ")"
                            : v);
        }
        b.append("            return new ")
                .append(t)
                .append("Result(")
                .append(String.join(", ", args))
                .append(");\n        }\n\n");
    }

    private static String convert(SchemaInfer.Type t, String expr) {
        return switch (t.kind()) {
            case TEXT -> "str(" + expr + ")";
            case NUMBER -> "num(" + expr + ")";
            case BOOL -> "bool(" + expr + ")";
            case ENUM -> t.enumName() + ".of(str(" + expr + "))";
        };
    }

    private static final String HELPERS =
            """
                    private static String str(Object o) {
                        return o == null ? null : String.valueOf(o);
                    }

                    private static Double num(Object o) {
                        if (o == null) return null;
                        if (o instanceof Number n) return n.doubleValue();
                        return Double.valueOf(String.valueOf(o).trim());
                    }

                    private static Boolean bool(Object o) {
                        if (o == null) return null;
                        if (o instanceof Boolean b) return b;
                        return Boolean.valueOf(String.valueOf(o).trim());
                    }
            """;
}

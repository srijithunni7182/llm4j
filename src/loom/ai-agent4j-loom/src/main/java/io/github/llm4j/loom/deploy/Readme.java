package io.github.llm4j.loom.deploy;

import java.util.Set;

/**
 * The operator's page: what this is, what it needs, what the review said, what happens when it
 * fails.
 */
final class Readme {

    private Readme() {}

    static String render(DeployPlan p, DeployOptions o, Set<String> files) {
        StringBuilder b = new StringBuilder();
        b.append("# Deploying ").append(o.name()).append("\n\n");
        b.append("Generated by `weave deploy` from `")
                .append(p.script())
                .append(
                        "`. It writes text only; nothing here has been built or started. The workflows: ")
                .append(String.join(", ", p.workflows()))
                .append(".\n\n");
        b.append("## Files\n\n");
        for (String f : files) if (!f.equals("README.md")) b.append("- `").append(f).append("`\n");
        b.append("\n## What it needs\n\n");
        if (p.envNames().isEmpty()) b.append("- No environment variables from the script.\n");
        for (String n : p.envNames())
            b.append("- `")
                    .append(n)
                    .append(
                            "` (a secret: set it in your secret store or `.env`; it is never written to a file here)\n");
        if (o.withFabric())
            b.append(
                    "- `LOOM_FABRIC_CLIENT_KEY`: this process's key for Fabric (`fabric client add`), as a secret.\n");
        b.append(
                "- `deploy/weave.jar`: the weave CLI of the same version, copied in before `docker build`.\n");
        if (!p.egressHosts().isEmpty())
            b.append("\nThe app talks to: ")
                    .append(String.join(", ", p.egressHosts()))
                    .append(".\n");
        if (p.localModels())
            b.append(
                    "\nA model runs on a local server (ollama): set `OLLAMA_HOST` and allow that address.\n");
        b.append("\n## What review said when this was generated\n\n")
                .append(o.reviewSummary() == null ? "Not run.\n" : o.reviewSummary() + "\n");
        b.append(
                "\nThe review never blocks a deployment. Run `weave review` for the details; `weave deploy --require-clean` makes open findings stop generation.\n");
        b.append("\n## When it fails\n\n");
        if (o.journal().equals("none"))
            b.append(
                    "- **Restart / node loss / volume loss**: no journal is kept, so a run in flight is lost.\n");
        else {
            b.append(
                            "- **Restart**: runs are journaled under `/data`; a run in flight resumes from its last step")
                    .append(p.asksAPerson() ? "; a run waiting for a person stays waiting" : "")
                    .append(".\n");
            b.append(
                    "- **Node loss**: the same, if `/data` is on storage that survives the node; otherwise as volume loss.\n");
            b.append(
                    "- **Volume loss**: runs in flight and their journals are gone; completed work done outside (a sent message, a refund) is not undone.\n");
        }
        if (!p.schedules().isEmpty())
            b.append("\nSchedules (")
                    .append(String.join(", ", p.schedules()))
                    .append(") are kept by `weave daemon`, which this image runs.\n");
        b.append("\n## Safety defaults\n\nNon-root user (")
                .append(Deploy.APP_UID)
                .append(
                        "), read-only root filesystem, all capabilities dropped, no ports published beyond what you asked for");
        if (o.withFabric())
            b.append(", Fabric on an internal network and published on loopback only");
        b.append(".\n");
        return b.toString();
    }
}

package io.github.llm4j.loom.review.tools;

import io.github.llm4j.loom.review.engine.RuleCatalog;
import io.github.llm4j.loom.review.engine.RuleInfo;
import io.github.llm4j.loom.review.model.Lens;
import io.github.llm4j.loom.review.pack.Pack;
import io.github.llm4j.loom.review.rule.ConditionText;
import io.github.llm4j.loom.review.rule.OptionTemplate;
import io.github.llm4j.loom.review.rule.RuleDoc;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * The pages of the rule reference, generated from the rules themselves (R69): one page per rule and
 * an index. A rule that comes from a pack carries its condition, escalations, fix and options as
 * well, written from the data, so a new rule needs no separate documentation. The output is
 * deterministic; a test compares it with the committed pages, so they cannot drift.
 */
public final class RuleDocs {

    private RuleDocs() {}

    /**
     * File name to page text, in a stable order: {@code index.md} first, then one file per rule.
     */
    public static Map<String, String> generate(Pack core, RuleCatalog catalog) {
        Map<String, RuleDoc> data = new LinkedHashMap<>();
        for (RuleDoc r : core.rules()) data.put(r.id(), r);
        List<RuleInfo> all = new ArrayList<>(catalog.all());
        all.sort(Comparator.comparing(RuleInfo::id));
        Map<String, String> pages = new LinkedHashMap<>();
        pages.put("index.md", index(all, data));
        for (RuleInfo i : all)
            pages.put(i.id().toLowerCase(java.util.Locale.ROOT) + ".md", page(i, data.get(i.id())));
        return pages;
    }

    private static String index(List<RuleInfo> all, Map<String, RuleDoc> data) {
        StringBuilder b = new StringBuilder();
        b.append("# Review rules\n\n");
        b.append(
                "Generated by `weave rules docs core`. Every rule `weave review` applies, grouped by lens. A rule marked *(off)* belongs to a lens that is off until you ask for it (`--lens +NAME`, or `--lens all`). See [how to write a rule](../WRITING_RULES.md).\n\n");
        for (Lens lens : Lens.values()) {
            List<RuleInfo> rules = all.stream().filter(r -> r.lens() == lens).toList();
            if (rules.isEmpty()) continue;
            b.append("## ")
                    .append(lens.title())
                    .append(lens.optional() ? " *(off)*" : "")
                    .append("\n\n");
            b.append("| Rule | Severity | What it looks for |\n|---|---|---|\n");
            for (RuleInfo r : rules)
                b.append("| [")
                        .append(r.id())
                        .append("](")
                        .append(r.id().toLowerCase(java.util.Locale.ROOT))
                        .append(".md) | ")
                        .append(r.severity() == null ? "varies" : r.severity().word())
                        .append(" | ")
                        .append(
                                cell(
                                        data.containsKey(r.id())
                                                ? data.get(r.id()).title()
                                                : r.title()))
                        .append(" |\n");
            b.append('\n');
        }
        return b.toString();
    }

    private static String page(RuleInfo i, RuleDoc d) {
        StringBuilder b = new StringBuilder();
        b.append("# ")
                .append(i.id())
                .append(": ")
                .append(plain(d != null ? d.title() : i.title()))
                .append("\n\n");
        b.append("- **Lens:** ")
                .append(i.lens().title())
                .append(i.lens().optional() ? " (off until asked for)" : "")
                .append('\n');
        b.append("- **Severity:** ").append(i.severity() == null ? "varies" : i.severity().word());
        if (d != null && !d.escalations().isEmpty()) {
            b.append(", raised to ");
            List<String> parts = new ArrayList<>();
            for (RuleDoc.Escalation e : d.escalations())
                parts.add(e.severity().word() + " when " + ConditionText.of(e.when()));
            b.append(String.join("; ", parts));
        }
        b.append('\n');
        b.append("- **From:** ")
                .append(i.source().startsWith("pack ") ? "the core rule pack" : i.source())
                .append('\n');
        if (d != null) {
            b.append("- **Applies to:** each ").append(d.about()).append('\n');
            if (d.since() != null) b.append("- **Since:** core ").append(d.since()).append('\n');
            if (d.heuristic())
                b.append(
                        "- **Heuristic:** yes, it guesses from names or wording, so it runs only with `heuristics = on` or when named in `review.properties`.\n");
        }
        b.append("\n");
        for (String line : i.explain().strip().split("\n"))
            if (!line.isBlank()) b.append(line.strip()).append("\n\n");
        if (d != null) {
            b.append("## When it fires\n\n");
            b.append("`").append(ConditionText.of(d.when())).append("`\n\n");
            if (!d.requires().isEmpty())
                b.append("Not evaluated unless the project declares: ")
                        .append(
                                String.join(
                                        ", ",
                                        d.requires().stream()
                                                .map(
                                                        r ->
                                                                "`"
                                                                        + r.replaceFirst(
                                                                                "^setting\\.", "")
                                                                        + "`")
                                                .toList()))
                        .append(" in `review.properties`.\n\n");
            if (d.fix() != null) {
                b.append("## Fix\n\n");
                b.append("`weave review --fix` ")
                        .append(
                                d.fix().safety() == io.github.llm4j.loom.review.model.FixSafety.SAFE
                                        ? "applies"
                                        : "shows (and applies only with `--yes`)")
                        .append(": ")
                        .append(plain(d.fix().label()))
                        .append(".\n\n");
            }
            if (!d.options().isEmpty()) {
                b.append("## Options\n\n");
                b.append(
                        "`weave review --assist` offers these, and you choose and give the values.\n\n");
                for (OptionTemplate o : d.options()) {
                    b.append("- **")
                            .append(o.id())
                            .append("**: ")
                            .append(plain(o.label()))
                            .append('.');
                    if (!o.explain().isBlank()) b.append(' ').append(o.explain().strip());
                    if (!o.asks().isEmpty()) {
                        List<String> q = new ArrayList<>();
                        for (OptionTemplate.Ask a : o.asks())
                            q.add(
                                    plain(a.prompt())
                                            + (a.defaultValue() == null
                                                    ? ""
                                                    : " (default `" + a.defaultValue() + "`)"));
                        b.append(" Asks: ").append(String.join("; ", q)).append('.');
                    }
                    b.append('\n');
                }
                b.append('\n');
            }
        }
        b.append("## Handle it without editing code\n\n");
        b.append(
                        "`weave review --accept FINGERPRINT --reason \"why\"` records that the finding is fine. `")
                .append(i.id())
                .append(" = off` in `review.properties` turns the rule off, and `")
                .append(i.id())
                .append(".severity = low` changes how loud it is.\n");
        return b.toString();
    }

    private static String plain(String template) {
        return template == null ? "" : template.replaceAll("\\{([^}]*)\\}", "`$1`");
    }

    private static String cell(String s) {
        return plain(s).replace("|", "\\|");
    }

    /** The page of one rule, for tests. */
    static Optional<String> pageOf(Map<String, String> pages, String id) {
        return Optional.ofNullable(pages.get(id.toLowerCase(java.util.Locale.ROOT) + ".md"));
    }
}

#!/usr/bin/env bash
# Regenerates the stats block in docs/ABOUT.md (between the stats:start and stats:end markers).
# Needs full git history (git fetch --unshallow, or actions/checkout with fetch-depth: 0).
# Usage: scripts/about-stats.sh          rewrite the block in place
#        scripts/about-stats.sh --print  print the block to stdout
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
DOC=docs/ABOUT.md

if [ "$(git rev-parse --is-shallow-repository)" = true ]; then
  echo "about-stats: shallow clone, commit counts would be wrong. Run: git fetch --unshallow" >&2
  exit 1
fi

round() { awk -v n="$1" 'BEGIN{printf "%d", int((n+500)/1000)*1000}'; }
lines() { xargs -r -0 cat | wc -l | tr -d ' '; }
fmt() { printf '%s' "$(printf '%d' "$1" | sed ':a;s/\B[0-9]\{3\}\>/,&/;ta')"; }

all=$(git ls-files -z | grep -zvE '\.(png|jpe?g|gif|ico|jar|woff2?|vsix|pdf)$' | lines)
jfiles=$(git ls-files '*.java' | wc -l | tr -d ' ')
jmain=$(git ls-files -z '*.java' | grep -zv '/src/test/' | lines)
jtest=$(git ls-files -z '*.java' | grep -z '/src/test/' | lines)
jall=$((jmain + jtest))
commits=$(git rev-list --count HEAD)
prs=$(git log --merges --format=%s | grep -c 'pull request' || true)
tests=$(git ls-files -z '*.java' | grep -z '/src/test/' | xargs -0 grep -hE '^\s*@(Test|ParameterizedTest|RepeatedTest)\b' | wc -l | tr -d ' ')
tclasses=$(git ls-files '*.java' | grep -c '/src/test/' || true)
loom=$(git ls-files '*.loom' | wc -l | tr -d ' ')
first=$(git log --reverse --format=%ad --date=short | sed -n 1p)
today=$(date -u +%F)

modules=""
while read -r n name; do
  r=$(( (n + 250) / 500 * 500 ))
  modules="${modules:+$modules · }${name} ~$(fmt "$r")"
done < <(for d in src/*/; do
  n=$(git ls-files -z "$d" | grep -zE '\.java$' | lines)
  [ "$n" -gt 0 ] && printf '%s %s\n' "$n" "$(basename "$d")"
done | sort -rn)

block=$(cat <<EOF
<!-- stats:start (generated by scripts/about-stats.sh; do not edit by hand) -->
*Counted from the repository on ${today}.*

| | |
|---|---|
| **Lines of code** (all tracked text files) | ~$(fmt "$(round "$all")") |
| Java | ~$(fmt "$(round "$jall")") lines in $(fmt "$jfiles") files (~$(fmt "$(round "$jmain")") main, ~$(fmt "$(round "$jtest")") test) |
| **Commits** | $(fmt "$commits") |
| **Merged pull requests** | $(fmt "$prs") |
| **Tests** | ~$(fmt "$(( (tests + 50) / 100 * 100 ))") (\`@Test\`, \`@ParameterizedTest\` and \`@RepeatedTest\` methods) across $(fmt "$tclasses") test classes |
| **Loom scripts** | $(fmt "$loom") \`.loom\` files (samples, starters and test fixtures) |
| **Age** | First commit on ${first} |

By module, in lines of Java (nearest 500): ${modules}.

Test code is almost as large as production code: about $(fmt "$(round "$jtest")") test lines against about $(fmt "$(round "$jmain")") main lines.
<!-- stats:end -->
EOF
)

if [ "${1:-}" = "--print" ]; then printf '%s\n' "$block"; exit 0; fi

grep -q '<!-- stats:start' "$DOC" && grep -q '<!-- stats:end -->' "$DOC" || { echo "about-stats: markers missing in $DOC" >&2; exit 1; }
tmp=$(mktemp)
awk -v block="$block" '
  /<!-- stats:start/ {print block; skip=1; next}
  /<!-- stats:end -->/ {skip=0; next}
  !skip {print}' "$DOC" > "$tmp"
mv "$tmp" "$DOC"
echo "about-stats: updated $DOC"
